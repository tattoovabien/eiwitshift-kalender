const T = (d: string, time = '10:00') => `${d}T${time}:00`;

type SeedMoment = Omit<Moment, 'customFields' | 'createdBy' | 'createdAt' | 'free' | 'region' | 'isGreenDealPartner' | 'halfhalfLink' | 'featured' | 'ongoing' | 'dateUnsure'> &
  Partial<Pick<Moment, 'customFields' | 'createdBy' | 'createdAt' | 'free' | 'region' | 'isGreenDealPartner' | 'halfhalfLink' | 'featured' | 'ongoing' | 'dateUnsure'>>;

function moment(m: SeedMoment): Moment {
  return {
    customFields: {},
    createdBy: m.organiser,
    createdAt: T('2026-09-01'),
    free: true,
    region: 'Vlaanderen',
    isGreenDealPartner: true,
    halfhalfLink: false,
    featured: false,
    ongoing: false,
    dateUnsure: false,
    ...m,
  };
}

