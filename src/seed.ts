export function seedState(): AppState {
  // Deep copy so the reducer can never mutate the seed.
  return JSON.parse(
    JSON.stringify({
      version: STATE_VERSION,
      role: 'coordinator',
      moments: SEED_MOMENTS,
      reactions: SEED_REACTIONS,
      comments: SEED_COMMENTS,
      signals: SEED_SIGNALS,
      notifications: SEED_NOTIFICATIONS,
      fieldDefs: SEED_FIELD_DEFS,
    } satisfies AppState),
  );
}
